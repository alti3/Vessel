    [Fact]
    public void Bundle_UsesPinnedModesAndHashChangesWithPorts()
    {
        var renderer = new TraefikRuntimeRenderer();

        ProxyRuntimeBundle standard = renderer.Render(RenderRequest(80, 443));
        ProxyRuntimeBundle custom = renderer.Render(RenderRequest(8080, 8443));

        Assert.NotEqual(standard.Hash, custom.Hash);
        Assert.Equal(standard.Hash, renderer.Render(RenderRequest(80, 443)).Hash);
        ProxyRuntimeFile acme = Assert.Single(standard.Files, file => file.RelativePath == ProxyLayout.AcmeStorageFile);
        Assert.True(acme.CreateOnly);
