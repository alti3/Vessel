            .Contents, StringComparison.Ordinal);
    }

    [Fact]
    public async Task LocalChannel_WritesAtomicallyWithModesAndKeepsCreateOnlyFiles()
    {
        using var root = new TemporaryDirectory();
        LocalServerFileChannel channel = LocalChannel(root.Path);
        ServerExecutionTarget target = Target(ServerConnectionType.Local);
        var ct = TestContext.Current.CancellationToken;

        await channel.EnsureDirectoryAsync(target, "proxy/acme", ServerFileModes.OwnerOnlyDirectory, ct);
        Assert.Equal(ServerFileWriteResult.Written, await channel.WriteAsync(target,
            new ServerFileWrite("proxy/dynamic/vessel-routes.yml", "v1", ServerFileModes.OwnerReadWrite), ct));
        await channel.WriteAsync(target,
            new ServerFileWrite("proxy/dynamic/vessel-routes.yml", "v2", ServerFileModes.OwnerReadWrite), ct);
        await channel.WriteAsync(target,
            new ServerFileWrite("proxy/acme/acme.json", "certs", ServerFileModes.OwnerReadWrite, true), ct);
        Assert.Equal(ServerFileWriteResult.AlreadyExists, await channel.WriteAsync(target,
            new ServerFileWrite("proxy/acme/acme.json", string.Empty, ServerFileModes.OwnerReadWrite, true), ct));

        Assert.Equal("v2", await channel.ReadTextAsync(target, "proxy/dynamic/vessel-routes.yml", ct));
        Assert.Equal("certs", await channel.ReadTextAsync(target, "proxy/acme/acme.json", ct));
        Assert.Null(await channel.ReadTextAsync(target, "proxy/missing.yml", ct));
        Assert.Empty(Directory.GetFiles(Path.Combine(root.Path, "proxy", "dynamic"), "*.tmp"));
        if (!OperatingSystem.IsWindows())
        {
            Assert.Equal(ServerFileModes.OwnerReadWrite,
                File.GetUnixFileMode(Path.Combine(root.Path, "proxy", "dynamic", "vessel-routes.yml")));
            Assert.Equal(ServerFileModes.OwnerOnlyDirectory,
                File.GetUnixFileMode(Path.Combine(root.Path, "proxy", "acme")));
        }
    }

