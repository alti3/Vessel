        Assert.Throws<NotSupportedException>(() => ssh.ResolveHostPath(Target(ServerConnectionType.Local), "proxy"));
    }

    [Fact]
    public async Task SshChannel_DeliversFilesThroughQuotedRemoteScriptRoundTrip()
    {
        if (OperatingSystem.IsWindows())
            return;

        // The fake SSH client executes the exact remote command string with a real POSIX shell, which proves the
        // quoting, the positional-argument script, atomic rename, modes and create-only semantics end to end.
        using var root = new TemporaryDirectory();
        var processRunner = new DotNetProcessRunner(new PassthroughRedactor(), TimeProvider.System);
        var sshClient = new LocalShellSshClient(processRunner);
        var channel = new SshServerFileChannel(Options(root.Path), new ServerCommandExecutor(processRunner, sshClient));
        ServerExecutionTarget target = Target(ServerConnectionType.Ssh);
        var ct = TestContext.Current.CancellationToken;
        const string contents = "http:\n  routers: {}\n  # it's $(not) `run` \"quoted\"\n";

        await channel.EnsureDirectoryAsync(target, ProxyLayout.AcmeDirectory, ServerFileModes.OwnerOnlyDirectory, ct);
        await channel.WriteAsync(target,
            new ServerFileWrite(ProxyLayout.DynamicConfigurationFile, contents, ServerFileModes.OwnerReadWrite), ct);
        Assert.Equal(ServerFileWriteResult.Written, await channel.WriteAsync(target,
            new ServerFileWrite(ProxyLayout.AcmeStorageFile, "certs", ServerFileModes.OwnerReadWrite, true), ct));
        Assert.Equal(ServerFileWriteResult.AlreadyExists, await channel.WriteAsync(target,
            new ServerFileWrite(ProxyLayout.AcmeStorageFile, string.Empty, ServerFileModes.OwnerReadWrite, true), ct));

        Assert.Equal(contents, await channel.ReadTextAsync(target, ProxyLayout.DynamicConfigurationFile, ct));
        Assert.Equal("certs", await channel.ReadTextAsync(target, ProxyLayout.AcmeStorageFile, ct));
        Assert.Null(await channel.ReadTextAsync(target, "proxy/missing.yml", ct));
        Assert.Equal(ServerFileModes.OwnerReadWrite,
            File.GetUnixFileMode(Path.Combine(root.Path, "proxy", "dynamic", "vessel-routes.yml")));
        Assert.Equal(ServerFileModes.OwnerOnlyDirectory, File.GetUnixFileMode(Path.Combine(root.Path, "proxy", "acme")));
        Assert.Empty(Directory.GetFiles(Path.Combine(root.Path, "proxy", "dynamic"), "*.tmp"));
        Assert.All(sshClient.Requests, request =>
        {
            Assert.Equal("example.com", request.Connection.Host);
            Assert.Equal("deploy", request.Connection.UserName);
            Assert.Equal(SshHostIdentityPolicy.RequireKnownHost, request.Connection.HostIdentityPolicy);
            Assert.StartsWith("'sh' '-c' ", request.Command, StringComparison.Ordinal);
        });
    }

