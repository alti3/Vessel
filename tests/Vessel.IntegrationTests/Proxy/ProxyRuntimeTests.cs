    [Fact]
    public void Channels_OnlyServeTheirConnectionTypes()
    {
        using var root = new TemporaryDirectory();
        LocalServerFileChannel local = LocalChannel(root.Path);
        var ssh = new SshServerFileChannel(Options(root.Path), new ServerCommandExecutor(
