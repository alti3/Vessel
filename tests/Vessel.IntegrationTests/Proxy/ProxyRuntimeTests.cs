    [Fact]
    public async Task Runtime_UsesStructuredComposeAndNetworkCommandsLocallyAndOverSsh()
    {
        var processRunner = new RecordingProcessRunner
        {
            Respond = command => command.Arguments.Contains("connect")
                ? (1, string.Empty, "endpoint with name vessel-proxy already exists in network vessel-abc")
                : (0, string.Empty, string.Empty)
        };
        var sshClient = new RecordingSshClient();
        var runtime = new DockerProxyContainerRuntime(new ServerCommandExecutor(processRunner, sshClient));
        var ct = TestContext.Current.CancellationToken;

        await runtime.UpAsync(Target(ServerConnectionType.Local), "/var/lib/vessel/proxy/docker-compose.yml", true,
            ct);
        await runtime.ConnectNetworkAsync(Target(ServerConnectionType.Local), "vessel-abc", ct);
        await runtime.ConnectNetworkAsync(Target(ServerConnectionType.Ssh), "vessel-abc", ct);
        await Assert.ThrowsAsync<ArgumentException>(() =>
            runtime.ConnectNetworkAsync(Target(ServerConnectionType.Local), "net; rm -rf /", ct));

        Assert.Equal(
            [
                "compose", "--project-name", "vessel-proxy", "--file", "/var/lib/vessel/proxy/docker-compose.yml",
                "up", "--detach", "--remove-orphans", "--force-recreate", "--wait", "--wait-timeout", "120"
            ],
            processRunner.Commands[0].Arguments);
        Assert.Equal(["network", "connect", "vessel-abc", "vessel-proxy"], processRunner.Commands[1].Arguments);
        SshCommandRequest remote = Assert.Single(sshClient.Requests);
        Assert.Equal("'docker' 'network' 'connect' 'vessel-abc' 'vessel-proxy'", remote.Command);
    }

