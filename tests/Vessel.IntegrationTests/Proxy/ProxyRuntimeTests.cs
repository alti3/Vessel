    private static ProxyRuntimeRenderRequest RenderRequest(int httpPort, int httpsPort)
    {
        return new ProxyRuntimeRenderRequest(FixedServerId, ComponentVersions.TraefikImage, httpPort, httpsPort,
            ProxyNaming.ServerNetwork(FixedServerId),
            new ProxyHostPaths("/var/lib/vessel/proxy/traefik.yml", "/var/lib/vessel/proxy/dynamic",
                "/var/lib/vessel/proxy/acme"));
    }

    private static YamlMappingNode Parse(string yaml)
    {
        var stream = new YamlStream();
        stream.Load(new StringReader(yaml));
        return (YamlMappingNode)stream.Documents[0].RootNode;
    }

    private static ServerExecutionTarget Target(ServerConnectionType connectionType)
    {
        return new ServerExecutionTarget(FixedServerId, connectionType, "example.com", 22, "deploy",
            ContainerRuntimeKind.Docker);
    }

    private static IOptions<ServerFilesOptions> Options(string root)
    {
        return Microsoft.Extensions.Options.Options.Create(new ServerFilesOptions
        {
            LocalRootDirectory = root,
            RemoteRootDirectory = OperatingSystem.IsWindows() ? "/var/lib/vessel" : root
        });
    }

    private static LocalServerFileChannel LocalChannel(string root)
    {
        return new LocalServerFileChannel(Options(root), new PathSafetyService());
    }

    private sealed class TemporaryDirectory : IDisposable
    {
        public TemporaryDirectory()
        {
            Path = System.IO.Path.Combine(System.IO.Path.GetTempPath(), $"vessel-proxy-{Guid.NewGuid():N}");
            Directory.CreateDirectory(Path);
        }

        public string Path { get; }

        public void Dispose()
        {
            if (Directory.Exists(Path))
                Directory.Delete(Path, true);
        }
    }

    private sealed class PassthroughRedactor : ISecretRedactor
    {
        public string Redact(string value, RedactionContext? context = null)
        {
            return value;
        }

        public byte[] RedactUtf8(byte[] value, RedactionContext? context = null)
        {
            return value;
        }
    }

    /// <summary>Stands in for OpenSSH: runs the remote command string with the local POSIX shell.</summary>
    private sealed class LocalShellSshClient(IProcessRunner processRunner) : ISshClient
    {
        public List<SshCommandRequest> Requests { get; } = [];

        public Task<bool> TestConnectionAsync(SshConnectionOptions options,
            CancellationToken cancellationToken = default)
        {
            return Task.FromResult(true);
        }

        public async Task<SshCommandResult> RunCommandAsync(SshCommandRequest request,
            CancellationToken cancellationToken = default)
        {
            Requests.Add(request);
            ProcessResult result = await processRunner.RunTextAsync(
                new ProcessCommand("sh", ["-c", request.Command], Timeout: TimeSpan.FromSeconds(30)),
                cancellationToken);
            return new SshCommandResult(result.ExitInfo.ExitCode, result.StandardOutput, result.StandardError);
        }

        public async Task<SshCommandResult> RunCommandWithInputAsync(SshCommandRequest request, Stream standardInput,
            CancellationToken cancellationToken = default)
        {
            Requests.Add(request);
            ProcessResult result = await processRunner.RunTextWithInputAsync(
                new ProcessCommand("sh", ["-c", request.Command], Timeout: TimeSpan.FromSeconds(30)),
                standardInput, cancellationToken);
            return new SshCommandResult(result.ExitInfo.ExitCode, result.StandardOutput, result.StandardError);
        }

        public Task UploadAsync(SshFileTransferRequest request, CancellationToken cancellationToken = default)
        {
            throw new NotSupportedException();
        }

        public Task DownloadAsync(SshFileTransferRequest request, CancellationToken cancellationToken = default)
        {
            throw new NotSupportedException();
        }
    }

