using System.Security.Cryptography;
using System.Text;
using Vessel.Application.Proxy;
using Vessel.Application.Servers.Files;
using Vessel.Domain.Proxy;
using YamlDotNet.Serialization;

namespace Vessel.Infrastructure.Proxy;

/// <summary>
///     Renders the Traefik static configuration and the proxy compose file (typed YAML through YamlDotNet).
///     Upstream reference: <c>bootstrap/helpers/proxy.php::generateDefaultProxyConfiguration</c>. Differences by design:
///     no Docker provider and no Docker socket mount (routes come only from Vessel's file provider), no API/dashboard,
///     and a static configuration file instead of command-line flags.
/// </summary>
public sealed class TraefikRuntimeRenderer : IProxyRuntimeRenderer
{
    public const string ContainerStaticConfigurationPath = "/etc/traefik/traefik.yml";
    public const string ContainerDynamicDirectory = "/etc/traefik/dynamic";
    public const string ContainerAcmeDirectory = "/etc/traefik/acme";
    public const string ContainerAcmeStorage = ContainerAcmeDirectory + "/acme.json";
    public const string CertificateResolver = "letsencrypt";
    public const string HttpEntryPoint = "web";
    public const string HttpsEntryPoint = "websecure";

    private const string Header = "# Generated by Vessel. Do not edit by hand.\n";

    private static readonly ISerializer Serializer = new SerializerBuilder()
        .WithQuotingNecessaryStrings()
        .DisableAliases()
        .Build();

    public ServerProxyType ProxyType => ServerProxyType.Traefik;

    public ProxyRuntimeBundle Render(ProxyRuntimeRenderRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);
        var staticConfiguration = RenderStaticConfiguration();
        var compose = RenderCompose(request);
        var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(
            $"{ProxyLayout.StaticConfigurationFile}\n{staticConfiguration}\n{ProxyLayout.ComposeFile}\n{compose}")))
            .ToLowerInvariant();

        return new ProxyRuntimeBundle(
            [
                new ProxyRuntimeDirectory(ProxyLayout.Directory, ServerFileModes.WorldReadableDirectory),
                new ProxyRuntimeDirectory(ProxyLayout.DynamicDirectory, ServerFileModes.WorldReadableDirectory),
                new ProxyRuntimeDirectory(ProxyLayout.AcmeDirectory, ServerFileModes.OwnerOnlyDirectory)
            ],
            [
                new ProxyRuntimeFile(ProxyLayout.StaticConfigurationFile, staticConfiguration,
                    ServerFileModes.WorldReadable),
                new ProxyRuntimeFile(ProxyLayout.ComposeFile, compose, ServerFileModes.WorldReadable),
                // Traefik refuses ACME storage that is readable by others; never overwrite issued certificates.
                new ProxyRuntimeFile(ProxyLayout.AcmeStorageFile, string.Empty, ServerFileModes.OwnerReadWrite, true)
            ],
            ProxyLayout.ComposeFile,
            hash);
    }

    public static string RenderStaticConfiguration()
    {
        var configuration = new Dictionary<string, object>
        {
            ["global"] = new Dictionary<string, object>
            {
                ["checkNewVersion"] = false,
                ["sendAnonymousUsage"] = false
            },
            ["log"] = new Dictionary<string, object> { ["level"] = "INFO" },
            // No "api" section: the Traefik API and dashboard stay disabled.
            ["ping"] = new Dictionary<string, object> { ["entryPoint"] = HttpEntryPoint },
            ["entryPoints"] = new Dictionary<string, object>
            {
                [HttpEntryPoint] = new Dictionary<string, object> { ["address"] = ":80" },
                [HttpsEntryPoint] = new Dictionary<string, object> { ["address"] = ":443" }
            },
            ["providers"] = new Dictionary<string, object>
            {
                ["file"] = new Dictionary<string, object>
                {
                    ["directory"] = ContainerDynamicDirectory,
                    ["watch"] = true
                }
            },
            ["certificatesResolvers"] = new Dictionary<string, object>
            {
                [CertificateResolver] = new Dictionary<string, object>
                {
                    ["acme"] = new Dictionary<string, object>
                    {
                        ["storage"] = ContainerAcmeStorage,
                        ["httpChallenge"] = new Dictionary<string, object> { ["entryPoint"] = HttpEntryPoint }
                    }
                }
            }
        };
        return (Header + Serializer.Serialize(configuration)).ReplaceLineEndings("\n");
    }

    public static string RenderCompose(ProxyRuntimeRenderRequest request)
    {
        var compose = new Dictionary<string, object>
        {
            ["name"] = ProxyNaming.ProxyComposeProject,
            ["services"] = new Dictionary<string, object>
            {
                ["traefik"] = new Dictionary<string, object>
                {
                    ["image"] = request.Image,
                    ["container_name"] = ProxyNaming.ProxyContainerName,
                    ["restart"] = "unless-stopped",
                    ["security_opt"] = new[] { "no-new-privileges:true" },
                    ["ports"] = new object[]
                    {
                        Port(80, request.HttpPort),
                        Port(443, request.HttpsPort)
                    },
                    ["volumes"] = new object[]
                    {
                        Bind(request.HostPaths.StaticConfigurationFile, ContainerStaticConfigurationPath, true),
                        // Mount the directory, not single files: atomic renames are only visible to the watcher
                        // through a directory bind mount.
                        Bind(request.HostPaths.DynamicDirectory, ContainerDynamicDirectory, true),
                        Bind(request.HostPaths.AcmeDirectory, ContainerAcmeDirectory, false)
                    },
                    ["networks"] = new[] { request.Network },
                    ["labels"] = new Dictionary<string, string>
                    {
                        ["vessel.managed"] = "true",
                        ["vessel.proxy"] = "true",
                        ["vessel.server-id"] = request.ServerId.Value.ToString("D")
                    },
                    ["healthcheck"] = new Dictionary<string, object>
                    {
                        ["test"] = new[] { "CMD", "traefik", "healthcheck", "--ping" },
                        ["interval"] = "10s",
                        ["timeout"] = "5s",
                        ["retries"] = 3,
                        ["start_period"] = "10s"
                    }
                }
            },
            ["networks"] = new Dictionary<string, object>
            {
                [request.Network] = new Dictionary<string, object> { ["external"] = true }
            }
        };
        return (Header + Serializer.Serialize(compose)).ReplaceLineEndings("\n");
    }

    private static Dictionary<string, object> Port(int target, int published)
    {
        return new Dictionary<string, object>
        {
            ["target"] = target,
            ["published"] = published,
            ["protocol"] = "tcp"
        };
    }

    private static Dictionary<string, object> Bind(string source, string target, bool readOnly)
    {
        return new Dictionary<string, object>
        {
            ["type"] = "bind",
            ["source"] = source,
            ["target"] = target,
            ["read_only"] = readOnly
        };
    }
}
